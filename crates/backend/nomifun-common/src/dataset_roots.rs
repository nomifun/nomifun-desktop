pub fn managed_dataset_roots() -> impl Iterator<Item = &'static ManagedDatasetRoot> {
    MANAGED_DATASET_ROOTS.iter()
}

/// Product-owned roots that belong to the reset/quarantine lifecycle.
pub fn reset_managed_dataset_roots() -> impl Iterator<Item = &'static ManagedDatasetRoot> {
    managed_dataset_roots().filter(|root| root.reset == ResetPolicy::Retire)
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;
    use std::path::{Component, Path};

    use super::*;

    #[test]
    fn registry_paths_are_unique_safe_top_level_paths() {
        let mut paths = BTreeSet::new();
        for root in MANAGED_DATASET_ROOTS {
            assert!(!root.path.is_empty());
            assert!(!root.path.starts_with('/'));
            assert!(!root.path.contains('\\'));
            assert!(!root.path.split('/').any(|segment| matches!(segment, "" | "." | "..")));
            assert!(
                matches!(
                    Path::new(root.path).components().collect::<Vec<_>>().as_slice(),
                    [Component::Normal(_)]
                ),
                "managed dataset roots must remain top-level no-follow leaves: {}",
                root.path
            );
            assert!(paths.insert(root.path), "duplicate managed dataset root: {}", root.path);
        }
    }

    #[test]
    fn reset_registry_preserves_only_host_control_files() {
        let preserved = managed_dataset_roots()
            .filter(|root| root.reset == ResetPolicy::Preserve)
            .map(|root| root.path)
            .collect::<Vec<_>>();
        assert_eq!(
            preserved,
            ["dir-config.json", WORK_ROOT_OWNER_FILE]
        );

        let retired = reset_managed_dataset_roots()
            .map(|root| root.path)
            .collect::<BTreeSet<_>>();
        assert_eq!(retired.len() + preserved.len(), MANAGED_DATASET_ROOTS.len());
        assert!(!retired.contains("dir-config.json"));
        assert!(!retired.contains(WORK_ROOT_OWNER_FILE));
        assert!(
            MANAGED_DATASET_ROOTS
                .iter()
                .filter(|root| {
                    root.path != "dir-config.json"
                        && root.path != WORK_ROOT_OWNER_FILE
                })
                .all(|root| retired.contains(root.path)),
            "every non-host-control root must remain reset-managed"
        );
    }
}
