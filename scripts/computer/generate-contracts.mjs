#!/usr/bin/env node
// The frozen worker inventory and its compact overrides own Computer contracts.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
import { digest, validateOverrides } from './freeze-tools.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const contracts = path.join(root, 'crates/backend/nomifun-agent-contracts/contracts');
const domain = path.join(root, 'crates/backend/nomifun-agent-domain-wave2/src');
const pascal = name => name.split('_').map(part => part[0].toUpperCase() + part.slice(1)).join('');
const quoted = JSON.stringify;

export function verifyInputs(inventory, overrides) {
  validateOverrides(overrides);
  if (inventory.schema_version !== 1 || inventory.overrides_sha256 !== digest(overrides)) throw new Error('Computer frozen inventory/profile drift; recapture the actual workers');
  if (inventory.tools.length !== overrides.tools.length) throw new Error('Computer frozen action count differs from profile');
  for (const tool of inventory.tools) {
    const profile = overrides.tools.find(item => item.driver_tool === tool.driver_tool);
    if (!profile || tool.action_id !== `computer/${tool.driver_tool}` || tool.model_tool !== `computer_${tool.driver_tool}`) throw new Error(`Invalid frozen action identity ${tool.driver_tool}`);
    for (const field of ['titles', 'descriptions', 'effect_class', 'resource_operation', 'loading', 'no_image', 'group', 'system_permissions']) {
      if (digest(tool[field]) !== digest(profile[field])) throw new Error(`Frozen profile drift ${tool.driver_tool}.${field}`);
    }
    if (!Object.keys(tool.platforms).length) throw new Error(`No actual platform schema for ${tool.driver_tool}`);
  }
}

export function generatedBlocks(inventory) {
  const tools = inventory.tools;
  const variants = tools.map(tool => `Computer${pascal(tool.driver_tool)}`);
  return {
    variants: variants.map(name => `    ${name} { input: StrictJsonValue },`).join('\n'),
    capability: variants.map((name, i) => `${i ? '            | ' : '            '}Self::${name} { .. }`).join('\n') + ' => COMPUTER_MODULE_ID,',
    actions: tools.map((tool, i) => `            Self::${variants[i]} { .. } => ${quoted(tool.action_id)},`).join('\n'),
    family: variants.map((name, i) => `${i ? '            | ' : '            '}Self::${name} { input }`).join('\n') + ' => {\n                Wave2CapabilityOperation::Computer { input: input.clone() }\n            }',
  };
}

export function generatedDomain(inventory) {
  const tools = inventory.tools;
  const identity = inventory.identity;
  const rows = tools.map(tool => ({ ...tool, variant: `Computer${pascal(tool.driver_tool)}` }));
  return `// @generated by scripts/computer/generate-contracts.mjs. Do not edit.
// Source: computer-tools.v1.json + computer-tools.overrides.v1.json.
pub const COMPUTER_PACKAGE_ID: &str = ${quoted(identity.package_id)};
pub const COMPUTER_MOUNT_ID: &str = ${quoted(identity.mount_id)};
pub const COMPUTER_CAPABILITY_IDS: &[&str] = &[COMPUTER_MODULE_ID];
pub const COMPUTER_ACTION_IDS: &[&str] = &[
${rows.map(tool => `    ${quoted(tool.action_id)},`).join('\n')}
];

const COMPUTER_ACTIONS: &[ActionDefinition] = &[
${rows.map(tool => `    ActionDefinition::function(${quoted(tool.action_id)}, EffectClass::${tool.effect_class}),`).join('\n')}
];

pub fn computer_resource_operation(action_id: &str) -> Option<&'static str> {
    match action_id {
${rows.map(tool => `        ${quoted(tool.action_id)} => Some(${quoted(tool.resource_operation)}),`).join('\n')}
        _ => None,
    }
}

fn computer_typed_operation(action_id: &str, input: StrictJsonValue) -> Option<Wave2TypedCapabilityOperation> {
    Some(match action_id {
${rows.map(tool => `        ${quoted(tool.action_id)} => Wave2TypedCapabilityOperation::${tool.variant} { input },`).join('\n')}
        _ => return None,
    })
}

impl Wave2TypedCapabilityOperation {
    /// Exact generated Computer action and its original untrusted input.
    pub fn computer_action(&self) -> Option<(&'static str, &StrictJsonValue)> {
        match self {
${rows.map(tool => `            Self::${tool.variant} { input } => Some((${quoted(tool.action_id)}, input)),`).join('\n')}
            _ => None,
        }
    }
}

fn computer_action_input_schema(action_id: &str) -> Option<StrictJsonValue> {
    static SCHEMAS: std::sync::OnceLock<BTreeMap<String, StrictJsonValue>> = std::sync::OnceLock::new();
    SCHEMAS.get_or_init(|| {
        let inventory: serde_json::Value = serde_json::from_str(include_str!(
            "../../../nomifun-agent-contracts/contracts/computer-tools.v1.json"
        )).expect("checked frozen Computer inventory");
        inventory["tools"].as_array().expect("frozen tools").iter().map(|tool| {
            let mut definitions = BTreeMap::new();
            for platform in tool["platforms"].as_object().expect("actual platform definitions").values() {
                let schema = platform["input_schema"].clone();
                definitions.insert(serde_json::to_string(&schema).expect("JSON schema"), schema);
            }
            let schemas: Vec<_> = definitions.into_values().collect();
            // Canonical authorization accepts captured native forms. Model
            // tooling selects its exact platform schema in nomifun-computer.
            let schema = if schemas.len() == 1 { schemas[0].clone() }
                else { serde_json::json!({ "anyOf": schemas }) };
            (tool["action_id"].as_str().expect("frozen action").to_owned(), StrictJsonValue(schema))
        }).collect()
    }).get(action_id).cloned()
}
`;
}

function replaceBlock(source, key, content) {
  const start = `// BEGIN GENERATED COMPUTER ${key}`;
  const end = `// END GENERATED COMPUTER ${key}`;
  const a = source.indexOf(start), b = source.indexOf(end);
  if (a < 0 || b < a) throw new Error(`Missing Computer generation boundary ${key}`);
  const indent = source.slice(source.lastIndexOf('\n', a) + 1, a);
  return source.slice(0, a + start.length) + '\n' + content + '\n' + indent + source.slice(b);
}

function formatRust(source) {
  const result = spawnSync('rustfmt', ['--edition', '2024', '--emit', 'stdout'], { input: source, encoding: 'utf8', windowsHide: true });
  if (result.error || result.status !== 0) throw new Error(`Computer Rust generation format failed: ${result.error ?? result.stderr}`);
  return result.stdout.replaceAll('\r\n', '\n');
}

export function derivePresentation(original, inventory) {
  return [...original.filter(tool => tool.capability_id !== inventory.identity.capability_id),
    ...inventory.tools.map(tool => ({ action_id: tool.action_id, capability_id: inventory.identity.capability_id, name: tool.model_tool, titles: tool.titles, target_fields: ['target', 'element_token', 'app', 'application', 'window_id', 'pid'] }))];
}

export function deriveSeed(seed, inventory) {
  const updated = structuredClone(seed);
  for (const key of ['assistant.general', 'companion.default']) {
    const selection = updated.templates[key].enabled_capabilities.find(item => item.capability.id === inventory.identity.capability_id);
    if (!selection) throw new Error(`Official template ${key} has no Computer selection`);
    selection.action_allowlist = inventory.tools.map(tool => tool.action_id).sort();
  }
  return updated;
}

export async function generate({ check = false } = {}) {
  const json = async name => JSON.parse(await readFile(path.join(contracts, name), 'utf8'));
  const [inventory, overrides, presentation, seed, targetInventory] = await Promise.all([
    json('computer-tools.v1.json'), json('computer-tools.overrides.v1.json'),
    json('tool-presentation.json'), json('presets/official-agent-seed-manifest.payload.json'),
    json('target-packages/first-party-agent-modules.v1.json'),
  ]);
  verifyInputs(inventory, overrides);
  let lib = await readFile(path.join(domain, 'lib.rs'), 'utf8');
  for (const [key, content] of Object.entries(generatedBlocks(inventory))) lib = replaceBlock(lib, key.toUpperCase(), content);
  const computerPackage = targetInventory.packages.find(item => item.capabilities.some(capability => capability.capability.id === inventory.identity.capability_id));
  if (!computerPackage) throw new Error('Computer package missing from first-party inventory');
  computerPackage.package.id = inventory.identity.package_id;
  computerPackage.source.source_identity = inventory.identity.package_id;
  const outputs = new Map([
    [path.join(domain, 'generated/computer.rs'), formatRust(generatedDomain(inventory))],
    [path.join(domain, 'lib.rs'), lib],
    [path.join(contracts, 'tool-presentation.json'), '[\n' + derivePresentation(presentation, inventory).map(tool => '  ' + JSON.stringify(tool)).join(',\n') + '\n]\n'],
    [path.join(contracts, 'presets/official-agent-seed-manifest.payload.json'), JSON.stringify(deriveSeed(seed, inventory), null, 2) + '\n'],
    [path.join(contracts, 'target-packages/first-party-agent-modules.v1.json'), JSON.stringify(targetInventory, null, 2) + '\n'],
  ]);
  for (const [file, contents] of outputs) {
    const existing = await readFile(file, 'utf8').catch(error => error.code === 'ENOENT' ? '' : Promise.reject(error));
    if (existing.replaceAll('\r\n', '\n') === contents.replaceAll('\r\n', '\n')) continue;
    if (check) throw new Error(`Computer generated artifact drift: ${path.relative(root, file)}`);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, contents);
  }
  console.log(`Computer contracts ${check ? 'checked' : 'generated'}: ${inventory.tools.length} actions, platforms=${Object.keys(inventory.captures).sort().join(',')}, source=${inventory.upstream.commit}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check')) throw new Error('usage: generate-contracts.mjs [--check]');
  await generate({ check: args.includes('--check') });
}
