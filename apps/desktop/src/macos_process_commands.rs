//! macOS process IPC enters the desktop's existing cleanup owner first.
//!
//! The plugin and command names are the official process plugin's names, so
//! its JS API and dependency-provided ACL manifest keep their existing scope.
//! Actual cleanup and restart handoff are injected by the desktop host.
use std::{future::Future, pin::Pin, sync::Arc};

use tauri::{AppHandle, Manager, Runtime, State, plugin::{Builder, TauriPlugin}};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum MacosProcessRequest {
    Exit { code: i32 },
    Restart,
}

pub(crate) type ProcessDispatch<R> = Arc<
    dyn Fn(AppHandle<R>, MacosProcessRequest)
        -> Pin<Box<dyn Future<Output = Result<(), String>> + Send>>
        + Send
        + Sync,
>;

struct Dispatcher<R: Runtime> {
    dispatch: ProcessDispatch<R>,
}

const RESERVED_EXIT_CODE_ERROR: &str = "PROCESS_EXIT_RESERVED_RESTART_CODE";

#[tauri::command]
async fn exit<R: Runtime>(
    app: AppHandle<R>,
    code: i32,
    dispatcher: State<'_, Dispatcher<R>>,
) -> Result<(), String> {
    // Exit must not open Tauri's non-cancellable restart-sentinel path.
    // Keep all other i32 values intact, matching the official command API.
    if code == tauri::RESTART_EXIT_CODE {
        return Err(RESERVED_EXIT_CODE_ERROR.into());
    }
    let dispatch = dispatcher.dispatch.clone();
    dispatch(app, MacosProcessRequest::Exit { code }).await
}

#[tauri::command]
async fn restart<R: Runtime>(
    app: AppHandle<R>,
    dispatcher: State<'_, Dispatcher<R>>,
) -> Result<(), String> {
    let dispatch = dispatcher.dispatch.clone();
    dispatch(app, MacosProcessRequest::Restart).await
}

pub(crate) fn init<R: Runtime>(dispatch: ProcessDispatch<R>) -> TauriPlugin<R> {
    Builder::new("process")
        .setup(move |app, _| {
            if !app.manage(Dispatcher { dispatch }) {
                return Err(std::io::Error::new(std::io::ErrorKind::AlreadyExists,
                    "macOS process command dispatcher is already registered").into());
            }
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![exit, restart])
        .build()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{collections::BTreeMap, sync::Mutex};
    use serde_json::{Value, json};
    use tauri::{
        ipc::{CallbackFn, CapabilityBuilder, InvokeBody},
        plugin::Plugin,
        test::{MockRuntime, get_ipc_response, mock_builder, mock_context, noop_assets},
        utils::acl::{manifest::Manifest, resolved::Resolved},
        webview::InvokeRequest,
    };

    fn context() -> tauri::Context<MockRuntime> {
        let mut manifests: BTreeMap<String, Manifest> = serde_json::from_str(include_str!(concat!(
            env!("CARGO_MANIFEST_DIR"), "/gen/schemas/acl-manifests.json"
        ))).expect("official dependency ACL manifests generated by the desktop build");
        let process = manifests.remove("process").expect("official process ACL manifest");
        let mut context = mock_context(noop_assets());
        *context.runtime_authority_mut() = tauri::runtime_authority!(
            BTreeMap::from([("process".into(), process)]), Resolved::default()
        );
        context.runtime_authority_mut().add_capability(
            CapabilityBuilder::new("macos-process-command-fixture")
                .webview("main").permission("process:default")
        ).expect("resolve official process permissions for the owned app document");
        context
    }

    fn request(command: &str, body: Value, url: &str) -> InvokeRequest {
        InvokeRequest {
            cmd: format!("plugin:process|{command}"),
            callback: CallbackFn(0), error: CallbackFn(1),
            url: url.parse().unwrap(), body: InvokeBody::Json(body),
            headers: Default::default(), invoke_key: tauri::test::INVOKE_KEY.into(),
        }
    }

    fn fixture(result: Result<(), String>) -> (tauri::App<MockRuntime>, Arc<Mutex<Vec<MacosProcessRequest>>>) {
        let calls = Arc::new(Mutex::new(Vec::new()));
        let recorded = calls.clone();
        let dispatch: ProcessDispatch<MockRuntime> = Arc::new(move |_, action| {
            recorded.lock().unwrap().push(action);
            let result = result.clone();
            Box::pin(async move { result })
        });
        let app = mock_builder().plugin(init(dispatch)).build(context()).unwrap();
        (app, calls)
    }

    #[test]
    fn macos_process_plugin_preserves_official_name_and_has_no_website_script() {
        let dispatch: ProcessDispatch<MockRuntime> = Arc::new(|_, _| Box::pin(async { Ok(()) }));
        let plugin = init(dispatch);
        assert_eq!(plugin.name(), "process");
        assert!(plugin.initialization_script().is_none());
        assert!(plugin.initialization_script_2().is_none());
    }

    #[test]
    fn macos_process_official_ipc_routes_enter_injected_cleanup_dispatch() {
        let (app, calls) = fixture(Ok(()));
        let view = tauri::WebviewWindowBuilder::new(&app, "main", Default::default()).build().unwrap();
        for (command, body) in [("exit", json!({"code": 7})), ("restart", json!({}))] {
            let response = get_ipc_response(&view, request(command, body, "tauri://localhost"))
                .expect("official route and permissions reach the injected dispatcher")
                .deserialize::<Value>().unwrap();
            assert_eq!(response, Value::Null);
        }
        assert_eq!(*calls.lock().unwrap(), [MacosProcessRequest::Exit { code: 7 }, MacosProcessRequest::Restart]);
    }

    #[test]
    fn macos_process_reserved_and_malformed_exit_never_dispatch() {
        let (app, calls) = fixture(Ok(()));
        let view = tauri::WebviewWindowBuilder::new(&app, "main", Default::default()).build().unwrap();
        let error = get_ipc_response(&view, request("exit", json!({"code": tauri::RESTART_EXIT_CODE}), "tauri://localhost"))
            .expect_err("reserved exit code cannot request raw restart");
        assert_eq!(error, json!(RESERVED_EXIT_CODE_ERROR));
        for body in [json!({}), json!({"code": "0"}), json!({"code": 2_147_483_648_i64})] {
            assert!(get_ipc_response(&view, request("exit", body, "tauri://localhost")).is_err());
        }
        assert!(calls.lock().unwrap().is_empty());
    }

    #[test]
    fn macos_process_cleanup_failure_rejects_the_official_restart_promise() {
        let (app, calls) = fixture(Err("fixture cleanup was not verified".into()));
        let view = tauri::WebviewWindowBuilder::new(&app, "main", Default::default()).build().unwrap();
        assert_eq!(get_ipc_response(&view, request("restart", json!({}), "tauri://localhost"))
            .expect_err("cleanup failure must reach the caller"), json!("fixture cleanup was not verified"));
        assert_eq!(*calls.lock().unwrap(), [MacosProcessRequest::Restart]);
    }

    #[test]
    fn macos_process_official_permissions_deny_remote_and_browser_documents() {
        let (app, calls) = fixture(Ok(()));
        let main = tauri::WebviewWindowBuilder::new(&app, "main", Default::default()).build().unwrap();
        let browser = tauri::WebviewWindowBuilder::new(&app, "browser-process-fixture", Default::default()).build().unwrap();
        assert!(get_ipc_response(&main, request("restart", json!({}), "https://example.com")).is_err());
        assert!(get_ipc_response(&browser, request("restart", json!({}), "tauri://localhost")).is_err());
        assert!(calls.lock().unwrap().is_empty());
    }
}
